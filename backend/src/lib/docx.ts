import {
  Document,
  Packer,
  Paragraph,
  TextRun,
  HeadingLevel,
  AlignmentType,
  BorderStyle,
  Table,
  TableRow,
  TableCell,
  WidthType
} from "docx";

export interface TranscriptDocxOptions {
  meetingTitle: string;
  audioFileName: string;
  generatedDate: string;
  detectedLanguage: string;
  transcriptText: string;
}

/**
 * Generates a clean, professional Microsoft Word (.docx) document buffer for a meeting transcript.
 */
export async function generateTranscriptDocx(options: TranscriptDocxOptions): Promise<Buffer> {
  const {
    meetingTitle,
    audioFileName,
    generatedDate,
    detectedLanguage,
    transcriptText
  } = options;

  const doc = new Document({
    sections: [
      {
        properties: {},
        children: [
          // Header Title
          new Paragraph({
            text: "Meeting Transcript",
            heading: HeadingLevel.HEADING_1,
            alignment: AlignmentType.CENTER,
            spacing: { after: 200 }
          }),

          new Paragraph({
            text: meetingTitle || "Executive Audio Recording",
            heading: HeadingLevel.HEADING_2,
            alignment: AlignmentType.CENTER,
            spacing: { after: 300 }
          }),

          // Metadata Table Box
          new Table({
            width: { size: 100, type: WidthType.PERCENTAGE },
            rows: [
              new TableRow({
                children: [
                  new TableCell({
                    width: { size: 30, type: WidthType.PERCENTAGE },
                    children: [new Paragraph({ children: [new TextRun({ text: "Audio File Name:", bold: true, color: "004AC6" })] })]
                  }),
                  new TableCell({
                    width: { size: 70, type: WidthType.PERCENTAGE },
                    children: [new Paragraph({ text: audioFileName || "audio_recording.mp3" })]
                  })
                ]
              }),
              new TableRow({
                children: [
                  new TableCell({
                    children: [new Paragraph({ children: [new TextRun({ text: "Generated Date:", bold: true, color: "004AC6" })] })]
                  }),
                  new TableCell({
                    children: [new Paragraph({ text: generatedDate || new Date().toLocaleString() })]
                  })
                ]
              }),
              new TableRow({
                children: [
                  new TableCell({
                    children: [new Paragraph({ children: [new TextRun({ text: "Detected Language:", bold: true, color: "004AC6" })] })]
                  }),
                  new TableCell({
                    children: [new Paragraph({ text: detectedLanguage || "English" })]
                  })
                ]
              })
            ]
          }),

          // Horizontal Divider
          new Paragraph({
            text: "----------------------------------------------------------------------------------------------------",
            alignment: AlignmentType.CENTER,
            spacing: { before: 300, after: 300 }
          }),

          // Transcript Section Header
          new Paragraph({
            text: "Transcript",
            heading: HeadingLevel.HEADING_2,
            spacing: { before: 200, after: 200 }
          }),

          // Format Paragraphs & Future-Ready Speaker Labels
          ...formatTranscriptParagraphs(transcriptText),

          // Footer Divider
          new Paragraph({
            text: "----------------------------------------------------------------------------------------------------",
            alignment: AlignmentType.CENTER,
            spacing: { before: 400, after: 200 }
          }),

          // Footer Branding
          new Paragraph({
            alignment: AlignmentType.CENTER,
            children: [
              new TextRun({ text: "Generated By ", italics: true, color: "737686" }),
              new TextRun({ text: "SlideNode AI Audio-to-Presentation Platform", bold: true, color: "004AC6" })
            ]
          })
        ]
      }
    ]
  });

  return await Packer.toBuffer(doc);
}

/**
 * Parses raw transcript string and splits into paragraphs.
 * Future-Ready: Formats speaker tags (e.g. "Speaker 1:", "John:") with bold styling.
 */
function formatTranscriptParagraphs(rawText: string): Paragraph[] {
  if (!rawText || !rawText.trim()) {
    return [
      new Paragraph({
        children: [new TextRun({ text: "No transcript available.", italics: true, color: "737686" })]
      })
    ];
  }

  const lines = rawText.split(/\r?\n+/).filter(line => line.trim().length > 0);
  const resultParagraphs: Paragraph[] = [];

  lines.forEach(line => {
    const trimmed = line.trim();
    // Check if line starts with Speaker Label e.g. "Speaker 1:" or "John Smith:"
    const speakerMatch = trimmed.match(/^(Speaker\s*\d+:?|[A-Z][a-z]+\s*[A-Z]?[a-z]*:)\s*(.*)/i);

    if (speakerMatch) {
      const speakerLabel = speakerMatch[1].endsWith(":") ? speakerMatch[1] : speakerMatch[1] + ":";
      const speakerSpeech = speakerMatch[2];

      resultParagraphs.push(
        new Paragraph({
          spacing: { after: 150 },
          children: [
            new TextRun({ text: `${speakerLabel} `, bold: true, color: "004AC6" }),
            new TextRun({ text: speakerSpeech })
          ]
        })
      );
    } else {
      resultParagraphs.push(
        new Paragraph({
          spacing: { after: 150 },
          children: [new TextRun({ text: trimmed })]
        })
      );
    }
  });

  return resultParagraphs;
}
